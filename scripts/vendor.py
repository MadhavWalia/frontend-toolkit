#!/usr/bin/env python3
"""Rebuild skills/frontend/library from the commits pinned in sources.json.

Only text a model reads is copied (.md, .css). Scripts, templates and binaries
are dropped, so nothing in the library can execute. Every file must pass
audit.py before it lands. Run with --check-updates to list upstream movement
without changing anything.
"""
import json, re, shutil, subprocess, sys, tempfile
from pathlib import Path

from audit import audit_tree

ROOT = Path(__file__).resolve().parent.parent
LIB = ROOT / "skills/frontend/library"
KEEP = {".md", ".css"}
LICENSES = ("LICENSE", "LICENSE.md", "LICENSE.txt")


def git(*args, cwd=None):
    return subprocess.run(["git", *args], cwd=cwd, check=True, text=True,
                          capture_output=True).stdout.strip()


def fetch(repo, commit, dest):
    git("init", "-q", str(dest))
    git("fetch", "-q", "--depth", "1", f"https://github.com/{repo}", commit, cwd=dest)
    git("-c", "advice.detachedHead=false", "checkout", "-q", "FETCH_HEAD", cwd=dest)


def describe(skill_md):
    text = skill_md.read_text(encoding="utf8")
    m = re.search(r"^description:\s*(?:[>|][-+]?\s*\n\s+)?[\"']?(.+?)[\"']?\s*$", text, re.M)
    first = m.group(1) if m else ""
    return re.split(r"(?<=[.!?])\s", first)[0].replace("|", "/")[:150]


def check_updates(cfg):
    for name, src in cfg["sources"].items():
        head = git("ls-remote", f"https://github.com/{src['repo']}", "HEAD").split()[0]
        state = "current" if head == src["commit"] else f"upstream at {head[:10]}"
        print(f"{name:14} {src['commit'][:10]}  {state}")


def main():
    cfg = json.loads((ROOT / "sources.json").read_text())
    if "--check-updates" in sys.argv:
        return check_updates(cfg)

    with tempfile.TemporaryDirectory() as tmp:
        tmp = Path(tmp)
        staged = tmp / "library"
        (staged / "licenses").mkdir(parents=True)
        for name, src in cfg["sources"].items():
            fetch(src["repo"], src["commit"], tmp / name)
            lic = next(tmp / name / f for f in LICENSES if (tmp / name / f).exists())
            shutil.copy(lic, staged / "licenses" / f"{name}.txt")

        rows, dropped = [], 0
        for area, by_source in cfg["skills"].items():
            for source, paths in by_source.items():
                for path, skill in paths.items():
                    src_dir, out = tmp / source / path, staged / area / skill
                    for f in sorted(p for p in src_dir.rglob("*") if p.is_file()):
                        if f.suffix.lower() in KEEP:
                            target = out / f.relative_to(src_dir)
                            target.parent.mkdir(parents=True, exist_ok=True)
                            shutil.copy(f, target)
                        else:
                            dropped += 1
                    rows.append((area, skill, source, describe(out / "SKILL.md")))

        problems = audit_tree(staged)
        if problems:
            print("\n".join(problems))
            sys.exit("audit failed: library left unchanged")

        lines = ["# Library index", "",
                 "Generated by scripts/vendor.py. Read `<area>/<skill>/SKILL.md` on demand.",
                 "Upstream scripts and templates were removed; if a skill points at one, "
                 "write the equivalent directly.", "",
                 "| Area | Skill | Source | Summary |", "|---|---|---|---|"]
        lines += [f"| {a} | {s} | {o} | {d} |" for a, s, o, d in sorted(rows)]
        (staged / "INDEX.md").write_text("\n".join(lines) + "\n", encoding="utf8")

        if LIB.exists():
            shutil.rmtree(LIB)
        shutil.copytree(staged, LIB)
        print(f"{len(rows)} skills vendored, {dropped} non-text files dropped")


if __name__ == "__main__":
    main()
